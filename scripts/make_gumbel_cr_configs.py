"""Configs and job lists of the Gumbel Top-(K+J) vs hard Top-K campaign (code residual).

Every run is configs/gumbel_cr/base.yaml (the code-carried hard Top-32 cell of
docs/kj-vs-hard-topk-code-residual.tex without the output norm, constant LR
after a 500-step warmup, checkpoints every 5000 steps) with the gate changed:

  hard/<scores>_k<K>.yaml                     hard Top-K, 20000 steps
  search/<scores>_k<K>_j<J>_t<tau>_l<lam>.yaml Gumbel Top-(K+J) with pool top_kj

<scores> is ``abs`` (abs_topk: the support is ranked by |a|) or ``sep``
(learned_score_topk: ranked by the separately computed s = W_s h + b_s, with
the support gradient).  A search run is stopped at step 2500 (job overrides:
--stop-step 2500, checkpoint every 2500); the controller
(scripts/gcr_controller.py) resumes the best setting of each (K, J) from that
checkpoint to 20000.

    python scripts/make_gumbel_cr_configs.py            # write the configs
    python scripts/make_gumbel_cr_configs.py --jobs abs # print abs job lines
"""
from __future__ import annotations

import argparse
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "configs", "gumbel_cr")

HARD_K = {"abs": [16, 32, 64, 128, 256], "sep": [16, 32, 64, 128]}
# (K, J) cells of the 20000-step grid (K + J in {32, 64, 128, 256}, J > 0)
GRID = [(16, 16), (16, 48), (16, 112), (16, 240), (32, 32), (32, 96), (32, 224),
        (64, 64), (64, 192)]
# cells with a (tau, lambda) search: every cell of the grid (2026-11-12, the
# user's request once the separate-score runs were paused; at first only six
# were searched and the other three borrowed a neighbour's setting)
SEARCH = list(GRID)
# cells without a search take the setting of one searched cell, or the setting
# with the best mean over two (no longer used)
BORROW: dict = {}
# score types whose search configs are written (the separate-score ones of the
# first grid stay in the repo for the runs they back)
SEARCH_SCORES = ["abs"]
# tau per score type: at initialization (K = 32, pool all N) these put about
# 10 %, 30 % and 60 % of the drawn support outside TopK(s)
# (analysis/gumbel_tau_calibration.py)
TAUS = {"abs": [0.2, 0.5, 1.2], "sep": [0.1, 0.3, 0.7]}
# lambda: the first grid {0, 0.01, 0.1, 1} collapsed every lambda > 0 to the
# unigram level within 2500 steps (and 1e-3 within 1000), so the search runs
# below the collapse; the runs of the first grid stay in the record
# (configs search/*_l0.01, _l0.1, _l1)
LAMBDAS = [0.0, 1e-5, 3e-5, 1e-4]
# 2026-11-12: the separate-score (sep) runs did not train in any tested
# configuration and were paused by the user; only abs runs are queued
MODE = {"abs": "abs_topk", "sep": "learned_score_topk"}
SEARCH_STOP = 2500

# Variants of the Gumbel runs: which bottlenecks sample in a training forward.
# "": all 8; "3f": 3 of the 8, one draw per forward (micro-batch); "3t": 3 of
# the 8, one draw per (sequence, position).  Run names gcr_gum<variant>_...,
# configs search<variant>/.  The lambda grids of 3f and 3t are set after their
# probe (PROBE_*: tau 0.5 at two cells, run as ordinary search runs).
VARIANTS = {"": (0, "forward"), "3f": (3, "forward"), "3t": (3, "token")}
PROBE_CELLS = [(16, 16), (32, 224)]
PROBE_TAUS = [0.5]
PROBE_LAMBDAS = [1e-5, 3e-5, 1e-4, 3e-4]
# set from the probe (2026-11-12): 3e-4 stalled (val CE ~2.95 / 3.46 at 2500),
# every lambda > 0 trailed hard Top-K; the all-gate grid is kept for comparability
LAMBDAS_3 = [0.0, 1e-5, 3e-5, 1e-4]

HEADER = ("# Generated by scripts/make_gumbel_cr_configs.py -- edit the script, not this file.\n"
          "# Campaign: Gumbel Top-(K+J) vs hard Top-K under the code residual (base.yaml).\n")


def fmt(x: float) -> str:
    return f"{x:g}"


def hard_name(scores: str, k: int) -> str:
    return f"gcr_hard_{scores}_k{k}"


def gum_name(scores: str, k: int, j: int, tau: float, lam: float, variant: str = "") -> str:
    return f"gcr_gum{variant}_{scores}_k{k}_j{j}_t{fmt(tau)}_l{fmt(lam)}"


def hard_path(scores, k):
    return os.path.join(OUT, "hard", f"{scores}_k{k}.yaml")


def search_path(scores, k, j, tau, lam, variant=""):
    return os.path.join(OUT, f"search{variant}",
                        f"{scores}_k{k}_j{j}_t{fmt(tau)}_l{fmt(lam)}.yaml")


def write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def write_all() -> int:
    n = 0
    for scores, ks in HARD_K.items():
        for k in ks:
            write(hard_path(scores, k), HEADER + (
                f"# hard Top-{k}, support ranked by "
                + ("|a|" if scores == "abs" else "s = W_s h + b_s (support gradient)") + "\n"
                f"_base_: ../base.yaml\n\ntrain:\n  run_name: {hard_name(scores, k)}\n\n"
                f"activation_bottleneck:\n  k: {k}\n  selection_mode: {MODE[scores]}\n"
                "  surrogate_mode: hard\n"))
            n += 1
    for scores in SEARCH_SCORES:
        n += write_search(scores, "", SEARCH, TAUS[scores], LAMBDAS)
    return n


def write_search(scores, variant, cells, taus, lambdas) -> int:
    n_gates, draw = VARIANTS[variant]
    n = 0
    for (k, j) in cells:
        for tau in taus:
            for lam in lambdas:
                gates = ("" if not n_gates else
                         f"  # {n_gates} of the 8 bottlenecks sample, drawn per {draw}\n"
                         f"  gumbel_gates_per_forward: {n_gates}\n"
                         f"  gumbel_gates_draw: {draw}\n")
                write(search_path(scores, k, j, tau, lam, variant), HEADER + (
                    f"# Gumbel Top-{k} drawn from the Top-{k + j} pool, tau {fmt(tau)}, "
                    f"lambda {fmt(lam)}"
                    + (f", {n_gates} of 8 bottlenecks per {draw}" if n_gates else "") + "\n"
                    "_base_: ../base.yaml\n\ntrain:\n"
                    f"  run_name: {gum_name(scores, k, j, tau, lam, variant)}\n"
                    "  # val/ce: deterministic TopK(s); val_stochastic/ce: 2 Gumbel draws\n"
                    "  policy_val_samples: 2\n  policy_val_seed: 1337\n\n"
                    f"activation_bottleneck:\n  k: {k}\n  j: {j}\n"
                    f"  selection_mode: {MODE[scores]}\n  surrogate_mode: hard\n"
                    "  gumbel_policy: true\n"
                    f"  gumbel_temperature: {fmt(tau)}\n  gumbel_policy_coef: {fmt(lam)}\n"
                    "  gumbel_pool: top_kj\n" + gates))
                n += 1
    return n


def rel(path: str) -> str:
    return os.path.relpath(path, ROOT)


def job_lines(scores: str, cells=None, hard=True, variant="", taus=None, lambdas=None):
    """Hard 20000-step runs first (longest), then the search cells in order."""
    lines = ([f"{hard_name(scores, k)}|{rel(hard_path(scores, k))}|" for k in HARD_K[scores]]
             if hard else [])
    for (k, j) in (cells or SEARCH):
        for tau in (taus or TAUS[scores]):
            for lam in (lambdas if lambdas is not None else LAMBDAS):
                lines.append(f"{gum_name(scores, k, j, tau, lam, variant)}|"
                             f"{rel(search_path(scores, k, j, tau, lam, variant))}|"
                             f"--stop-step {SEARCH_STOP} --train.checkpoint_every_steps={SEARCH_STOP}")
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", choices=list(MODE))
    ap.add_argument("--cells", nargs="*", default=None, help="K,J pairs (default: SEARCH)")
    ap.add_argument("--no-hard", action="store_true")
    ap.add_argument("--variant", default="", choices=list(VARIANTS))
    ap.add_argument("--taus", type=float, nargs="+", default=None)
    ap.add_argument("--lambdas", type=float, nargs="+", default=None)
    ap.add_argument("--write", action="store_true",
                    help="write the search configs of --variant/--cells/--taus/--lambdas")
    args = ap.parse_args()
    cells = [tuple(map(int, c.split(","))) for c in args.cells] if args.cells else None
    if args.write:
        n = write_search("abs", args.variant, cells or SEARCH, args.taus or TAUS["abs"],
                         args.lambdas if args.lambdas is not None else LAMBDAS)
        print(f"wrote {n} configs under {rel(OUT)}/search{args.variant}")
    elif args.jobs:
        print("\n".join(job_lines(args.jobs, cells, hard=not args.no_hard,
                                   variant=args.variant, taus=args.taus,
                                   lambdas=args.lambdas)))
    else:
        print(f"wrote {write_all()} configs under {rel(OUT)}")


if __name__ == "__main__":
    main()
