"""Configs and job lists of the Gumbel Top-(K+J) vs hard Top-K campaign (code residual).

Every run is configs/gumbel_cr/base.yaml (the code-carried hard Top-32 cell of
docs/kj-vs-hard-topk-code-residual.tex without the output norm, constant LR
after a 500-step warmup, checkpoints every 5000 steps) with the gate changed:

  hard/<scores>_k<K>.yaml                     hard Top-K, 20000 steps
  search/<scores>_k<K>_j<J>_t<tau>_l<lam>.yaml Gumbel Top-(K+J) with pool top_kj

<scores> is ``abs`` (abs_topk: the support is ranked by |a|) or ``sep``
(learned_score_topk: ranked by the separately computed s = W_s h + b_s, with
the support gradient).  A search run is stopped at step 2500 (job overrides:
--stop-step 2500, checkpoint every 2500); the controller
(scripts/gcr_controller.py) resumes the best setting of each searched (K, J)
from that checkpoint to 20000 and starts the other (K, J) cells with the
setting of their closest searched cell.

    python scripts/make_gumbel_cr_configs.py            # write the configs
    python scripts/make_gumbel_cr_configs.py --jobs abs # print abs job lines
"""
from __future__ import annotations

import argparse
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "configs", "gumbel_cr")

HARD_K = {"abs": [16, 32, 64, 128, 256], "sep": [16, 32, 64, 128]}
# (K, J) cells of the 20000-step grid (K + J in {32, 64, 128, 256}, J > 0)
GRID = [(16, 16), (16, 48), (16, 112), (16, 240), (32, 32), (32, 96), (32, 224),
        (64, 64), (64, 192)]
# cells with a (tau, lambda) search, in queue order
SEARCH = [(16, 16), (16, 240), (32, 32), (32, 224), (64, 64), (64, 192)]
# the other cells take the setting of: one searched cell, or the setting with
# the best mean over two (equally close) searched cells
BORROW = {(16, 48): [(16, 16)], (16, 112): [(16, 240)], (32, 96): [(32, 32), (32, 224)]}
# tau per score type: at initialization (K = 32, pool all N) these put about
# 10 %, 30 % and 60 % of the drawn support outside TopK(s)
# (analysis/gumbel_tau_calibration.py)
TAUS = {"abs": [0.2, 0.5, 1.2], "sep": [0.1, 0.3, 0.7]}
# lambda: the first grid {0, 0.01, 0.1, 1} collapsed every lambda > 0 to the
# unigram level within 2500 steps (and 1e-3 within 1000), so the search runs
# below the collapse; the runs of the first grid stay in the record
# (configs search/*_l0.01, _l0.1, _l1)
LAMBDAS = [0.0, 1e-5, 3e-5, 1e-4]
# 2026-11-12: the separate-score (sep) runs did not train in any tested
# configuration and were paused by the user; only abs runs are queued
MODE = {"abs": "abs_topk", "sep": "learned_score_topk"}
SEARCH_STOP = 2500

HEADER = ("# Generated by scripts/make_gumbel_cr_configs.py -- edit the script, not this file.\n"
          "# Campaign: Gumbel Top-(K+J) vs hard Top-K under the code residual (base.yaml).\n")


def fmt(x: float) -> str:
    return f"{x:g}"


def hard_name(scores: str, k: int) -> str:
    return f"gcr_hard_{scores}_k{k}"


def gum_name(scores: str, k: int, j: int, tau: float, lam: float) -> str:
    return f"gcr_gum_{scores}_k{k}_j{j}_t{fmt(tau)}_l{fmt(lam)}"


def hard_path(scores, k):
    return os.path.join(OUT, "hard", f"{scores}_k{k}.yaml")


def search_path(scores, k, j, tau, lam):
    return os.path.join(OUT, "search", f"{scores}_k{k}_j{j}_t{fmt(tau)}_l{fmt(lam)}.yaml")


def write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def write_all() -> int:
    n = 0
    for scores, ks in HARD_K.items():
        for k in ks:
            write(hard_path(scores, k), HEADER + (
                f"# hard Top-{k}, support ranked by "
                + ("|a|" if scores == "abs" else "s = W_s h + b_s (support gradient)") + "\n"
                f"_base_: ../base.yaml\n\ntrain:\n  run_name: {hard_name(scores, k)}\n\n"
                f"activation_bottleneck:\n  k: {k}\n  selection_mode: {MODE[scores]}\n"
                "  surrogate_mode: hard\n"))
            n += 1
    for scores in MODE:
        for (k, j) in SEARCH:
            for tau in TAUS[scores]:
                for lam in LAMBDAS:
                    write(search_path(scores, k, j, tau, lam), HEADER + (
                        f"# Gumbel Top-{k} drawn from the Top-{k + j} pool, tau {fmt(tau)}, "
                        f"lambda {fmt(lam)}\n"
                        "_base_: ../base.yaml\n\ntrain:\n"
                        f"  run_name: {gum_name(scores, k, j, tau, lam)}\n"
                        "  # val/ce: deterministic TopK(s); val_stochastic/ce: 2 Gumbel draws\n"
                        "  policy_val_samples: 2\n  policy_val_seed: 1337\n\n"
                        f"activation_bottleneck:\n  k: {k}\n  j: {j}\n"
                        f"  selection_mode: {MODE[scores]}\n  surrogate_mode: hard\n"
                        "  gumbel_policy: true\n"
                        f"  gumbel_temperature: {fmt(tau)}\n  gumbel_policy_coef: {fmt(lam)}\n"
                        "  gumbel_pool: top_kj\n"))
                    n += 1
    return n


def rel(path: str) -> str:
    return os.path.relpath(path, ROOT)


def job_lines(scores: str, cells=None, hard=True):
    """Hard 20000-step runs first (longest), then the search cells in order."""
    lines = ([f"{hard_name(scores, k)}|{rel(hard_path(scores, k))}|" for k in HARD_K[scores]]
             if hard else [])
    for (k, j) in (cells or SEARCH):
        for tau in TAUS[scores]:
            for lam in LAMBDAS:
                lines.append(f"{gum_name(scores, k, j, tau, lam)}|"
                             f"{rel(search_path(scores, k, j, tau, lam))}|"
                             f"--stop-step {SEARCH_STOP} --train.checkpoint_every_steps={SEARCH_STOP}")
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", choices=list(MODE))
    ap.add_argument("--cells", nargs="*", default=None, help="K,J pairs (default: SEARCH)")
    ap.add_argument("--no-hard", action="store_true")
    args = ap.parse_args()
    if args.jobs:
        cells = [tuple(map(int, c.split(","))) for c in args.cells] if args.cells else None
        print("\n".join(job_lines(args.jobs, cells, hard=not args.no_hard)))
    else:
        print(f"wrote {write_all()} configs under {rel(OUT)}")


if __name__ == "__main__":
    main()
